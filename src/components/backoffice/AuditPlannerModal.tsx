import React, { useState } from 'react';
import {
  Calendar,
  Building,
  Users,
  Layers,
  Filter,
  Check,
  X,
  Lock,
} from 'lucide-react';
import type { AuditType, Store, User } from '../../types';

interface AuditPlannerModalProps {
  stores: Store[];
  users: User[];
  onClose: () => void;
  onCreateAudit: (payload: {
    storeId: string;
    type: AuditType;
    date: string;
    assignedAuditorIds: string[];
    assignedBackOfficeIds: string[];
    productSelectionType: 'all' | 'category' | 'company' | 'not_audited_days';
    filterValue?: string;
    notes?: string;
  }) => Promise<void>;
}

export const AuditPlannerModal: React.FC<AuditPlannerModalProps> = ({
  stores,
  users,
  onClose,
  onCreateAudit,
}) => {
  const [storeId, setStoreId] = useState(stores[0]?.id || '');
  const [auditType, setAuditType] = useState<AuditType>('QUARTERLY FULL AUDIT');
  const [date, setDate] = useState(new Date().toISOString().slice(0, 10));
  const [productSelectionType, setProductSelectionType] = useState<
    'all' | 'category' | 'company' | 'not_audited_days'
  >('all');
  const [filterValue, setFilterValue] = useState('');
  const [assignedAuditorIds, setAssignedAuditorIds] = useState<string[]>([]);
  const [assignedBackOfficeIds, setAssignedBackOfficeIds] = useState<string[]>([]);
  const [notes, setNotes] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  const selectedStore = stores.find((s) => s.id === storeId) || stores[0];
  const autoGeneratedName = selectedStore
    ? `${selectedStore.name.split(' ')[0].toUpperCase()} / ${auditType} / ${date}`
    : '';

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!storeId) {
      alert('Please select a store branch.');
      return;
    }
    if (assignedAuditorIds.length === 0) {
      alert('Please assign at least one field auditor.');
      return;
    }
    setIsSubmitting(true);
    try {
      await onCreateAudit({
        storeId,
        type: auditType,
        date,
        assignedAuditorIds,
        assignedBackOfficeIds,
        productSelectionType,
        filterValue,
        notes,
      });
      onClose();
    } finally {
      setIsSubmitting(false);
    }
  };

  const toggleAuditor = (id: string) => {
    setAssignedAuditorIds((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]
    );
  };

  const toggleBackOffice = (id: string) => {
    setAssignedBackOfficeIds((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]
    );
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-4 backdrop-blur-xs overflow-y-auto">
      <div className="w-full max-w-2xl bg-white rounded-3xl overflow-hidden shadow-2xl border border-blue-100 my-8">
        {/* Header */}
        <div className="p-5 bg-[#0B3D91] text-white flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-white/20 flex items-center justify-center">
              <Calendar className="w-5 h-5 text-white" />
            </div>
            <div>
              <h3 className="text-base sm:text-lg font-black tracking-tight text-white">
                Plan New Stock Audit Cycle
              </h3>
              <p className="text-xs text-blue-200">
                Auto-generates standardized naming and snapshots cutoff bills.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 text-blue-200 hover:text-white rounded-lg min-h-[44px] min-w-[44px] flex items-center justify-center"
            aria-label="Close"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Auto Name Preview Card */}
        <div className="p-4 bg-[#F7FAFF] border-b border-blue-100 flex items-center justify-between gap-3">
          <div className="flex items-center gap-2 text-xs">
            <span className="font-bold text-slate-500 uppercase tracking-wider">
              Auto Audit Name:
            </span>
            <span className="font-mono font-black text-[#0B3D91] bg-blue-100/70 px-2.5 py-1 rounded-md text-xs sm:text-sm">
              {autoGeneratedName}
            </span>
          </div>
          <span className="text-[11px] text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded font-semibold border border-emerald-200">
            STORE / TYPE / DATE
          </span>
        </div>

        <form onSubmit={handleSubmit} className="p-6 space-y-5">
          {/* Row 1: Store & Type */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1.5">
                Target Store Branch
              </label>
              <select
                value={storeId}
                onChange={(e) => setStoreId(e.target.value)}
                className="w-full px-3 py-2.5 text-xs sm:text-sm rounded-xl border border-blue-200 bg-slate-50 focus:bg-white focus:ring-2 focus:ring-[#1D5FD1] min-h-[44px]"
              >
                <option value="" disabled>Select a store branch</option>
                {stores.map((s) => (
                  <option key={s.id} value={s.id}>
                    {s.name} ({s.code})
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1.5">
                Audit Type
              </label>
              <select
                value={auditType}
                onChange={(e) => setAuditType(e.target.value as AuditType)}
                className="w-full px-3 py-2.5 text-xs sm:text-sm rounded-xl border border-blue-200 bg-slate-50 focus:bg-white focus:ring-2 focus:ring-[#1D5FD1] min-h-[44px]"
              >
                <option value="QUARTERLY FULL AUDIT">QUARTERLY FULL AUDIT</option>
                <option value="MONTHLY CYCLE COUNT">MONTHLY CYCLE COUNT</option>
                <option value="HIGH-VALUE NARCOTICS">HIGH-VALUE NARCOTICS</option>
                <option value="SPOT RECOUNT">SPOT RECOUNT</option>
              </select>
            </div>
          </div>

          {/* Row 2: Date & Product Selection Filter */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1.5">
                Audit Execution Date
              </label>
              <input
                type="date"
                value={date}
                onChange={(e) => setDate(e.target.value)}
                required
                className="w-full px-3 py-2 text-xs sm:text-sm rounded-xl border border-blue-200 bg-slate-50 focus:bg-white min-h-[44px]"
              />
            </div>

            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1.5">
                Product Selection Criteria
              </label>
              <select
                value={productSelectionType}
                onChange={(e) =>
                  setProductSelectionType(
                    e.target.value as 'all' | 'category' | 'company' | 'not_audited_days'
                  )
                }
                className="w-full px-3 py-2.5 text-xs sm:text-sm rounded-xl border border-blue-200 bg-slate-50 focus:bg-white min-h-[44px]"
              >
                <option value="all">All Store Products</option>
                <option value="category">By Medicine Category</option>
                <option value="company">By Manufacturer / Company</option>
                <option value="not_audited_days">Not Audited in &gt;60 Days</option>
              </select>
            </div>
          </div>

          {/* Conditional Filter Value input */}
          {productSelectionType === 'category' && (
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1">
                Category Name
              </label>
              <input
                type="text"
                value={filterValue}
                onChange={(e) => setFilterValue(e.target.value)}
                placeholder="e.g. Antibiotics, Cardiovascular, Antidiabetic"
                required
                className="w-full px-3 py-2 text-xs rounded-xl border border-blue-200 bg-slate-50 min-h-[44px]"
              />
            </div>
          )}

          {productSelectionType === 'company' && (
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1">
                Company Name
              </label>
              <input
                type="text"
                value={filterValue}
                onChange={(e) => setFilterValue(e.target.value)}
                placeholder="e.g. Cipla Ltd, GlaxoSmithKline, Sun Pharmaceutical"
                required
                className="w-full px-3 py-2 text-xs rounded-xl border border-blue-200 bg-slate-50 min-h-[44px]"
              />
            </div>
          )}

          {/* Auditor Assignment Section */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4 pt-2 border-t border-slate-100">
            {/* Field Auditors */}
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2 flex items-center gap-1.5">
                <Users className="w-3.5 h-3.5 text-[#1D5FD1]" />
                <span>Assign Field Auditors</span>
              </label>
              <div className="space-y-1.5 max-h-36 overflow-y-auto">
                {users
                  .filter((u) => u.role === 'auditor')
                  .map((u) => (
                    <label
                      key={u.id}
                      className="flex items-center gap-2 p-2 rounded-xl border border-slate-200 hover:bg-blue-50/50 cursor-pointer text-xs"
                    >
                      <input
                        type="checkbox"
                        checked={assignedAuditorIds.includes(u.id)}
                        onChange={() => toggleAuditor(u.id)}
                        className="rounded text-[#1D5FD1] focus:ring-[#1D5FD1]"
                      />
                      <div>
                        <span className="font-bold text-slate-800">{u.name}</span>
                        <span className="text-[10px] text-slate-400 block">{u.employeeId}</span>
                      </div>
                    </label>
                  ))}
              </div>
            </div>

            {/* Back-Office Reviewers */}
            <div>
              <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2 flex items-center gap-1.5">
                <Users className="w-3.5 h-3.5 text-[#0B3D91]" />
                <span>Assign Back-Office Auditors</span>
              </label>
              <div className="space-y-1.5 max-h-36 overflow-y-auto">
                {users
                  .filter((u) => u.role === 'back office' || u.role === 'admin')
                  .map((u) => (
                    <label
                      key={u.id}
                      className="flex items-center gap-2 p-2 rounded-xl border border-slate-200 hover:bg-blue-50/50 cursor-pointer text-xs"
                    >
                      <input
                        type="checkbox"
                        checked={assignedBackOfficeIds.includes(u.id)}
                        onChange={() => toggleBackOffice(u.id)}
                        className="rounded text-[#1D5FD1] focus:ring-[#1D5FD1]"
                      />
                      <div>
                        <span className="font-bold text-slate-800">{u.name}</span>
                        <span className="text-[10px] text-slate-400 block capitalize">{u.role}</span>
                      </div>
                    </label>
                  ))}
              </div>
            </div>
          </div>

          {/* Notes */}
          <div>
            <label className="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-1">
              Audit Scope Notes (Optional)
            </label>
            <input
              type="text"
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              placeholder="e.g. Pay special attention to cold chain insulin and narcotics safe."
              className="w-full px-3 py-2 text-xs rounded-xl border border-slate-200 bg-slate-50 focus:bg-white min-h-[44px]"
            />
          </div>

          {/* Snapshot Lock Notice */}
          <div className="bg-blue-50 p-3 rounded-xl border border-blue-200 text-xs text-blue-900 flex items-center gap-2">
            <Lock className="w-4 h-4 text-[#1D5FD1] shrink-0" />
            <span>
              Creating this audit will immediately lock system ERP snapshot and capture the cutoff bill number.
            </span>
          </div>

          {/* Buttons */}
          <div className="flex items-center gap-3 pt-3">
            <button
              type="button"
              onClick={onClose}
              className="flex-1 py-3 px-4 rounded-xl border border-slate-200 text-slate-700 font-bold text-xs sm:text-sm hover:bg-slate-50 min-h-[48px]"
            >
              Cancel
            </button>
            <button
              type="submit"
              disabled={isSubmitting}
              className="flex-1 py-3 px-4 rounded-xl bg-[#1D5FD1] hover:bg-[#0B3D91] text-white font-bold text-xs sm:text-sm shadow-md shadow-blue-500/20 transition min-h-[48px]"
            >
              {isSubmitting ? 'Initializing Cycle...' : 'Create Audit & Lock Snapshot'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
